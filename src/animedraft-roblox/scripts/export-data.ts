/**
 * Generates src/shared/Data.luau from the AnimeDraft web app's character database,
 * so the Roblox game and the website always share the same roster and power scaling.
 * Run from animedraft-roblox/:  npm --prefix ../animedraft-next exec tsx scripts/export-data.ts
 */
import { writeFileSync } from "node:fs";
import { CHARACTERS, ACTIVE_SERIES, LEVELS, SPEEDS, INTELLECT, HAX, WEIGHT } from "../../animedraft-next/src/data";

const s = (v: string) => JSON.stringify(v); // JSON string literals are valid Luau strings
const list = (xs: readonly string[]) => `{ ${xs.map(s).join(", ")} }`;
const hex = (h: string) => {
  const n = parseInt(h.slice(1), 16);
  return `Color3.fromRGB(${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255})`;
};

let out = `--!strict
-- GENERATED by scripts/export-data.ts from animedraft-next/src/data. Do not edit by hand.

local Data = {}

Data.LEVELS = ${list(LEVELS)}
Data.SPEEDS = ${list(SPEEDS)}
Data.INTELLECT = ${list(INTELLECT)}
Data.HAX = ${list(HAX)}
Data.WEIGHT = { ap = ${WEIGHT.ap}, dur = ${WEIGHT.dur}, spd = ${WEIGHT.spd}, iq = ${WEIGHT.iq}, hax = ${WEIGHT.hax} }
Data.BEYOND_LEVEL = 16

Data.SERIES = {
`;
for (const x of ACTIVE_SERIES)
  out += `\t${x.key} = { key = ${s(x.key)}, name = ${s(x.name)}, short = ${s(x.short)}, c1 = ${hex(x.colors[0])}, c2 = ${hex(x.colors[1])} },\n`;
out += `}\n\nData.CHARACTERS = {\n`;
for (const c of CHARACTERS) {
  const k = c.scaling;
  out += `\t{ key = ${s(c.key)}, name = ${s(c.name)}, series = ${s(c.series)}, title = ${s(c.title)}, initials = ${s(c.initials)},
\t\trating = ${c.rating}, tier = ${s(c.tier)},
\t\tstats = { pow = ${c.stats.pow}, spd = ${c.stats.spd}, iq = ${c.stats.iq}, dur = ${c.stats.dur}, sup = ${c.stats.sup} },
\t\tscaling = { ap = ${k.ap}, dur = ${k.dur}, spd = ${k.spd}, iq = ${k.iq}, hax = ${k.hax} },
\t\tfeat = ${s(k.feat)} },\n`;
}
out += `}

Data.BY_KEY = {}
for _, c in Data.CHARACTERS do
\tData.BY_KEY[c.key] = c
end

function Data.get(key: string)
\treturn Data.BY_KEY[key]
end

return Data
`;
writeFileSync(new URL("../src/shared/Data.luau", import.meta.url), out);
console.log(`Wrote ${CHARACTERS.length} characters, ${ACTIVE_SERIES.length} series`);
