#!/usr/bin/env python3
"""Bulk-uploads character portraits to Roblox and wires them into the game.

Only upload images you have the rights to use.

    1. Put one image per character in portraits/raw/, named by id (see list.md), e.g. gojo.png
    2. Create an Open Cloud API key: create.roblox.com -> Open Cloud -> API Keys -> Create API Key
         - Access permissions: "Assets" API -> Read + Write
         - Accepted IP addresses: 0.0.0.0/0 (or your own IP)
    3. Run (from animedraft-roblox/):
         ROBLOX_API_KEY=xxxx ROBLOX_USER_ID=1234567 python3 scripts/upload-portraits.py

It shrinks every image to 256x256 (scripts/prepare-portraits.py), uploads each one as a Decal, waits for
Roblox to finish processing, and writes src/shared/Portraits.luau (id -> asset id). Already-uploaded files
are remembered in portraits/uploaded.json, so you can stop and re-run it any time; changed images are
uploaded again. Afterwards run `python3 scripts/build-place.py` and update the live place (README).
"""
import hashlib
import json
import os
import subprocess
import sys
import time
import urllib.error
import urllib.request
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UPLOAD_DIR = ROOT / "portraits" / "upload"
STATE = ROOT / "portraits" / "uploaded.json"
OUT = ROOT / "src" / "shared" / "Portraits.luau"
API = "https://apis.roblox.com/assets/v1"

key = os.environ.get("ROBLOX_API_KEY", "").strip()
user = os.environ.get("ROBLOX_USER_ID", "").strip()
if not key or not user.isdigit():
    sys.exit("Set ROBLOX_API_KEY and ROBLOX_USER_ID (your numeric Roblox user id). See the top of this file.")


def call(method, url, body=None, headers=None):
    req = urllib.request.Request(url, data=body, method=method, headers={"x-api-key": key, **(headers or {})})
    for attempt in range(6):
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                return json.loads(r.read() or b"{}")
        except urllib.error.HTTPError as e:
            if e.code in (429, 500, 502, 503) and attempt < 5:
                time.sleep(2 ** attempt)  # rate limited or busy: back off and retry
                continue
            raise SystemExit(f"{method} {url} failed: HTTP {e.code} {e.read().decode(errors='replace')[:300]}")


def upload(path: Path) -> int:
    meta = {
        "assetType": "Decal",
        "displayName": f"AnimeDraft {path.stem}"[:50],
        "description": "AnimeDraft character portrait",
        "creationContext": {"creator": {"userId": user}},
    }
    boundary = uuid.uuid4().hex
    body = (
        f'--{boundary}\r\nContent-Disposition: form-data; name="request"\r\n\r\n{json.dumps(meta)}\r\n'
        f'--{boundary}\r\nContent-Disposition: form-data; name="fileContent"; filename="{path.name}"\r\n'
        f"Content-Type: image/jpeg\r\n\r\n"
    ).encode() + path.read_bytes() + f"\r\n--{boundary}--\r\n".encode()
    op = call("POST", f"{API}/assets", body, {"Content-Type": f"multipart/form-data; boundary={boundary}"})
    op_path = op.get("path") or f"operations/{op.get('operationId')}"
    for _ in range(60):  # wait for processing (usually a few seconds)
        res = call("GET", f"{API}/{op_path}")
        if res.get("done"):
            asset = res.get("response", {}).get("assetId")
            if not asset:
                raise SystemExit(f"Upload of {path.name} finished without an asset id: {res}")
            return int(asset)
        time.sleep(2)
    raise SystemExit(f"Timed out waiting for {path.name}")


def write_luau(ids):
    lines = "\n".join(f'\t["{k}"] = {v},' for k, v in sorted(ids.items()))
    OUT.write_text(
        "--!strict\n-- GENERATED by scripts/upload-portraits.py: character key -> Roblox asset id.\n"
        f"return {{\n{lines}\n}} :: {{ [string]: number }}\n",
        encoding="utf-8",
    )


subprocess.run([sys.executable, str(ROOT / "scripts" / "prepare-portraits.py")], check=True)
state = json.loads(STATE.read_text()) if STATE.exists() else {}
files = sorted(UPLOAD_DIR.glob("*.jpg"))
if not files:
    sys.exit("No images found. Put them in portraits/raw/ named by id (see list.md).")

for i, f in enumerate(files, 1):
    digest = hashlib.sha1(f.read_bytes()).hexdigest()
    done = state.get(f.stem)
    if done and done.get("sha1") == digest:
        continue
    print(f"[{i}/{len(files)}] uploading {f.stem} ...", flush=True)
    state[f.stem] = {"id": upload(f), "sha1": digest}
    STATE.write_text(json.dumps(state, indent=1))  # save progress after every image
    write_luau({k: v["id"] for k, v in state.items()})

write_luau({k: v["id"] for k, v in state.items()})
print(f"Done: {len(state)} portraits in {OUT.relative_to(ROOT)}. Next: python3 scripts/build-place.py, then update the live place.")
